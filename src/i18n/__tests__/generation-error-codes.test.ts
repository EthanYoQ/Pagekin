const sourceFiles = () => ['electron', 'src'].flatMap(dir => repoSourceFiles(dir))
  .filter(file => !file.includes('/__tests__/') && !file.startsWith('src/i18n/') && /\.tsx?$/u.test(file))

const CODE_LITERAL = new RegExp(`['"\`]((?:${COVERED_PREFIXES.join('|')})[A-Z0-9_]*[A-Z0-9])['"\`]`, 'gu')

function coveredCodesInSource(): Map<string, string> {
  const codes = new Map<string, string>()
  for (const file of sourceFiles()) {
    for (const match of readFileSync(join(REPO_ROOT, file), 'utf8').matchAll(CODE_LITERAL)) {
      if (!codes.has(match[1]!)) codes.set(match[1]!, file)
    }
  }
  return codes
}

const unregistered = new Set(Object.values(UNREGISTERED).flat())
const isRegistered = (code: string) => knownAppErrorMessage(shown('zh-CN'), code) !== undefined

describe('error codes that reach the workflow failure panel', () => {
  const codes = coveredCodesInSource()

  it('finds the codes the scan is meant to cover', () => {
    expect(codes.has('GENERATION_SOURCE_CHANGED')).toBe(true)
    expect(codes.has('LEGACY_ROSTER_GENERATION_CANCELLED')).toBe(true)
    expect(codes.size).toBeGreaterThan(300)
  })

  it('registers or explicitly exempts every code the source can raise', () => {
    const uncovered = [...codes].filter(([code]) => !isRegistered(code) && !unregistered.has(code))
      .map(([code, file]) => `${code} (${file})`)
    expect(uncovered, '在 app-errors.ts 登记文案，或在本文件按理由列为不登记').toEqual([])
  })

  it('keeps the exemption list free of registered or vanished codes', () => {
    expect([...unregistered].filter(isRegistered)).toEqual([])
    expect([...unregistered].filter(code => !codes.has(code))).toEqual([])
    expect(Object.values(UNREGISTERED).flat()).toHaveLength(unregistered.size)
  })
})
